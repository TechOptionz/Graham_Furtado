// Pre-computes the Queensland map used on /about into static SVG path data,
// so d3-geo, topojson and the world atlas never ship to the browser.
// Mirrors the projection in design/About.dc.html. Run: npm run generate:map
import { writeFileSync, mkdirSync, readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { geoGraticule, geoMercator, geoPath } from 'd3-geo';
import { feature } from 'topojson-client';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
// 10m (1:10,000,000) Natural Earth coastline: Moreton Bay, Hervey Bay, K'gari and the Gulf read as real
// geography. The projection's clipExtent trims everything outside the frame, so the output stays small.
const topo = JSON.parse(readFileSync(resolve(root, 'node_modules/world-atlas/countries-10m.json'), 'utf8'));
const countries = feature(topo, topo.objects.countries).features;
const aus = countries.find((f) => f.id === '036' || f.properties.name === 'Australia');
if (!aus) throw new Error('Australia not found in world-atlas');

const W = 600;
const H = 630;

// Queensland extent (statutory meridians/parallels; ocean edges clipped by coastline). Clockwise for d3-geo.
const qld = {
  type: 'Feature',
  geometry: {
    type: 'Polygon',
    coordinates: [[
      [153.55, -28.17], [152.5, -28.42], [151.5, -28.85], [150.0, -28.96], [148.95, -29.0], [141.0, -29.0],
      [141.0, -26.0], [138.0, -26.0], [138.0, -9.5], [155.5, -9.5], [155.5, -28.17], [153.55, -28.17],
    ]],
  },
};
const frame = {
  type: 'Feature',
  geometry: { type: 'Polygon', coordinates: [[[137.5, -29.5], [137.5, -10.5], [154.5, -10.5], [154.5, -29.5], [137.5, -29.5]]] },
};
const border = {
  type: 'LineString',
  coordinates: [[153.55, -28.17], [152.5, -28.42], [151.5, -28.85], [150.0, -28.96], [148.95, -29.0], [141.0, -29.0], [141.0, -26.0], [138.0, -26.0], [138.0, -16.5]],
};

const proj = geoMercator()
  .fitExtent([[W * 0.01, H * 0.06], [W * 0.69, H * 0.94]], frame)
  .clipExtent([[0, 0], [W, H]]);
const path = geoPath(proj).digits(1);
const pt = (lon, lat) => proj([lon, lat]).map((v) => Math.round(v * 10) / 10);

// Graticule every 5°, drawn as fine ocean lines behind the land.
const graticule = geoGraticule().step([5, 5]).extent([[130, -35], [160, -5]])();

const [bx, by] = pt(153.03, -27.47);
const seqRadius = Math.round(Math.abs(pt(153.03, -25.9)[1] - by) * 10) / 10;

const data = {
  width: W,
  height: H,
  australia: path(aus),
  graticule: path(graticule),
  queensland: path(qld),
  border: path(border),
  seq: { cx: bx, cy: by, r: seqRadius },
  places: {
    bargara: pt(152.46, -24.82),
    brisbane: [bx, by],
  },
  // Sea labels (anchor points only; the component sets the type).
  seas: {
    coralSea: pt(152.2, -17.3),
    gulf: pt(139.9, -14.6),
    tasman: pt(153.9, -29.1),
  },
};

const out = resolve(root, 'content/generated/queensland-map.ts');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// GENERATED by scripts/generate-queensland-map.mjs — do not edit by hand.\n` +
    `// Source: world-atlas countries-10m (Natural Earth), Mercator projection.\n` +
    `export const queenslandMap = ${JSON.stringify(data, null, 2)} as const;\n`,
);
console.log(`Wrote ${out} (${Math.round(JSON.stringify(data).length / 1024)} KB)`);
